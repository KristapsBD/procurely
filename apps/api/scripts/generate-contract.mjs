// Publishes the API contract and regenerates the client types from it.
//
//   pnpm --filter @procurely/api contract:generate   writes apps/api/openapi.json and
//                                                     packages/shared-types/src/generated/api.ts
//   pnpm --filter @procurely/api contract:check      fails if either file differs from what the
//                                                     API would generate now (used by CI)
//
// Both build the API first (`nest build`, which applies the Swagger plugin to the DTOs and
// controllers) and read the compiled app, so no database is needed.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { NestFactory } from '@nestjs/core';
import openapiTS, { astToString } from 'openapi-typescript';

process.env.NODE_ENV ??= 'test';
await import('reflect-metadata');
const { AppModule } = await import('../dist/app.module.js');
const { createOpenApiDocument } = await import('../dist/contract/openapi.js');

const root = new URL('../../../', import.meta.url);
const outputs = {
  'apps/api/openapi.json': null,
  'packages/shared-types/src/generated/api.ts': null,
};

const app = await NestFactory.create(AppModule, { logger: false });
const document = createOpenApiDocument(app);
await app.close();

outputs['apps/api/openapi.json'] = `${JSON.stringify(document, null, 2)}\n`;
const ast = await openapiTS(document, { alphabetize: true });
outputs['packages/shared-types/src/generated/api.ts'] =
  `/* eslint-disable */\n// Generated by \`pnpm --filter @procurely/api contract:generate\` from the API. Do not edit.\n\n${astToString(ast)}`;

const check = process.argv.includes('--check');
let drifted = false;
for (const [path, content] of Object.entries(outputs)) {
  const file = fileURLToPath(new URL(path, root));
  if (check) {
    let current = null;
    try {
      current = readFileSync(file, 'utf8');
    } catch {
      // a missing file counts as drift
    }
    if (current !== content) {
      drifted = true;
      console.error(`DRIFT: ${path} differs from what the API generates`);
    }
  } else {
    writeFileSync(file, content);
    console.log(`wrote ${path}`);
  }
}
if (drifted) {
  console.error(
    'Run `pnpm --filter @procurely/api contract:generate` and commit the result.',
  );
  process.exit(1);
}
if (check) console.log('API contract and shared client types are in sync');
